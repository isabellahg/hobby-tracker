import { useState } from 'react'
import { applyBatch } from '../../domain/operations/registry'
import { makeContext } from '../../domain/operations/context'
import { describeChanges } from '../../domain/operations/diff'
import type { OperationBatchRequest, OperationResult } from '../../domain/operations/envelope'
import { runBatch } from '../../state/actions'
import { ChangePreviewList } from '../../components/ChangePreviewList'

const EXAMPLE = JSON.stringify(
  {
    version: 1,
    operations: [
      { operation: 'taskDef.create', payload: { label: 'Collect references' } },
      { operation: 'taskDef.create', payload: { label: 'Sketch silhouette' } },
      { operation: 'taskDef.create', payload: { label: 'Thumbnail 5 poses', parentId: '$ref:1' } },
      {
        operation: 'routine.create',
        payload: { name: 'Boss recreation', taskDefIds: ['$ref:0', '$ref:1'] },
      },
    ],
  },
  null,
  2,
)

function parseBatch(raw: string): OperationBatchRequest {
  const parsed = JSON.parse(raw)
  if (parsed.version !== 1 || !Array.isArray(parsed.operations)) {
    throw new Error('Expected { "version": 1, "operations": [...] }')
  }
  return parsed as OperationBatchRequest
}

function ResultList({ results }: { results: OperationResult[] }) {
  return (
    <div className="stack stack-sm">
      {results.map((r, i) => (
        <div key={i} className={r.success ? 'card card-tight' : 'card card-tight card-error'}>
          <div className="row row-between">
            <strong>{r.operation}</strong>
            <span className={r.success ? 'text-success' : 'text-danger'}>
              {r.success ? 'OK' : 'Failed'}
            </span>
          </div>
          {r.summary && <p className="desc m0">{r.summary}</p>}
          {r.errors && (
            <ul className="list-bullets text-danger">
              {r.errors.map((e, j) => (
                <li key={j}>
                  {e.path}: {e.message}
                </li>
              ))}
            </ul>
          )}
          {r.changes.length > 0 && <ChangePreviewList lines={describeChanges(r.changes)} />}
        </div>
      ))}
    </div>
  )
}

export function ImportScreen() {
  const [raw, setRaw] = useState('')
  const [parseError, setParseError] = useState<string | null>(null)
  const [preview, setPreview] = useState<OperationResult[] | null>(null)
  const [applied, setApplied] = useState<OperationResult[] | null>(null)
  const [pendingBatch, setPendingBatch] = useState<OperationBatchRequest | null>(null)

  async function handlePreview() {
    setParseError(null)
    setApplied(null)
    setPreview(null)
    let batch: OperationBatchRequest
    try {
      batch = parseBatch(raw)
    } catch (err) {
      setParseError(err instanceof Error ? err.message : 'Invalid JSON')
      return
    }
    const result = await applyBatch(batch, makeContext({ dryRun: true }))
    setPreview(result.results)
    setPendingBatch(batch)
  }

  async function handleApply() {
    if (!pendingBatch) return
    const result = await runBatch(pendingBatch)
    setApplied(result.results)
    setPreview(null)
  }

  function reset() {
    setPreview(null)
    setApplied(null)
    setPendingBatch(null)
  }

  return (
    <div className="stack">
      <div className="page-header">
        <h2>LLM Import</h2>
      </div>
      <p className="desc m0">
        Paste a batch of operations generated by an LLM. Nothing is written until you review the preview
        and explicitly confirm — and there is no operation that can fabricate a calendar mark directly;
        marks only ever follow from a real finished session.
      </p>

      <div className="card stack">
        <textarea
          rows={12}
          placeholder={EXAMPLE}
          value={raw}
          onChange={(e) => setRaw(e.target.value)}
          className="code-input"
        />
        <div className="row">
          <button type="button" className="btn btn-primary" onClick={handlePreview} disabled={!raw.trim()}>
            Preview
          </button>
          <button type="button" className="btn" onClick={() => setRaw(EXAMPLE)}>
            Load example
          </button>
          {(preview || applied) && (
            <button type="button" className="btn" onClick={reset}>
              Clear
            </button>
          )}
        </div>
        {parseError && <p className="error">{parseError}</p>}
      </div>

      {preview && (
        <div className="stack">
          <h3>Preview — nothing applied yet</h3>
          <ResultList results={preview} />
          <div className="row">
            <button
              type="button"
              className="btn btn-primary"
              onClick={handleApply}
              disabled={preview.some((r) => !r.success)}
            >
              Apply these changes
            </button>
          </div>
          {preview.some((r) => !r.success) && (
            <p className="error">Fix the failing operation(s) above before applying.</p>
          )}
        </div>
      )}

      {applied && (
        <div className="stack">
          <h3>Applied</h3>
          <ResultList results={applied} />
        </div>
      )}
    </div>
  )
}
